-- ============================================================================
-- BELLYBAND (SPANDAN) - HINDSIGHT AI MEMORY DATABASE MIGRATION
-- Database: bellyband_db
-- Character Set: utf8mb4 (Full multilingual support)
-- ============================================================================
-- Description:
-- Adds a lightweight table `hindsight_memories` to map Vectorize Hindsight AI
-- memory identifiers to patient accounts (users) with interaction timestamps.
-- 
-- Backward Compatibility:
-- - Uses CREATE TABLE IF NOT EXISTS.
-- - Does NOT modify, rename, or drop any existing tables or columns.
-- - Foreign key links to `users`(`id`) with CASCADE to match existing conventions
--   (kick_logs, symptom_logs, appointments, user_sessions).
-- ============================================================================

CREATE DATABASE IF NOT EXISTS `bellyband_db`
  CHARACTER SET utf8mb4 
  COLLATE utf8mb4_unicode_ci;

USE `bellyband_db`;

-- ----------------------------------------------------------------------------
-- Table: hindsight_memories
-- Maps Hindsight AI memory IDs to patient IDs and interaction timestamps.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `hindsight_memories` (
  `id` BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  
  -- Patient reference (maps directly to users.id)
  `patient_id` INT UNSIGNED NOT NULL,
  
  -- External memory ID generated by Hindsight API (Vectorize)
  `hindsight_memory_id` VARCHAR(128) NOT NULL,
  
  -- Timestamp of when the patient interaction occurred
  `interaction_timestamp` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  
  -- Interaction context/channel: 'chat', 'symptom', 'vitals', 'appointment', 'notes'
  `interaction_type` VARCHAR(50) NOT NULL DEFAULT 'chat',
  
  -- Optional lightweight local preview/summary for quick dashboard retrieval
  `summary` VARCHAR(500) NULL,
  
  -- Optional JSON/text metadata (e.g. tags, trimester, sentiment, confidence score)
  `metadata` TEXT NULL,
  
  -- Record audit timestamps
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  -- Foreign Key Constraint (Referential integrity with existing users table)
  CONSTRAINT `fk_hindsight_patient_id`
    FOREIGN KEY (`patient_id`) REFERENCES `users` (`id`)
    ON DELETE CASCADE ON UPDATE CASCADE,

  -- Performance & Look-up Indexes
  UNIQUE KEY `uk_patient_memory` (`patient_id`, `hindsight_memory_id`),
  INDEX `idx_hindsight_patient_time` (`patient_id`, `interaction_timestamp`),
  INDEX `idx_hindsight_memory_id` (`hindsight_memory_id`),
  INDEX `idx_hindsight_type` (`interaction_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


